const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const moduleExports = {};
const source = fs.readFileSync("src/lib/performance/audit.ts", "utf8");
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, { exports: moduleExports, URL });
const classify = moduleExports.classifyPageSpeedFailure;
const quota = classify(403, { error: { status: "RESOURCE_EXHAUSTED", errors: [{ reason: "dailyLimitExceeded" }] } }, false);
assert.equal(quota.httpStatus, 429);
assert.equal(quota.code, "quota");
assert(!quota.message.includes("clé API non autorisée"));
const missing = classify(403, { error: { status: "PERMISSION_DENIED" } }, false);
assert.equal(missing.code, "missing_key");
assert.match(missing.message, /PAGESPEED_API_KEY/);
const restricted = classify(403, { error: { status: "PERMISSION_DENIED" } }, true);
assert.equal(restricted.code, "permission");
const invalid = classify(400, { error: { errors: [{ reason: "API_KEY_INVALID" }] } }, true);
assert.equal(invalid.code, "invalid_key");
const unavailable = classify(503, null, true);
assert.equal(unavailable.httpStatus, 502);
assert.doesNotMatch(unavailable.message, /AIza|Bearer/);
console.log("PageSpeed API: quota, missing/restricted/invalid key, unavailable upstream OK");
